/**
 * زبان برنامه از روی Context (برای لایه‌های غیرکامپوزی مثل اعلان‌ها،
 * ویجت‌ها و سرویس‌ها)؛ از نسخه هم‌گامِ نگهداری‌شده در Application خوانده
 * می‌شود تا نیازی به خواندن ناهمگام DataStore نباشد.
 */
fun appLangForContext(context: Context): AppLang =
    appLangOf((context.applicationContext as? GeofenceAlertApp)?.currentLanguageKey ?: "fa")

/** رشته‌های زبان ذخیره‌شده برای لایه‌های غیرکامپوزی. */
fun stringsForContext(context: Context): UiStrings = stringsFor(appLangForContext(context))

private val AR_DIGITS = charArrayOf('٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩')

/** بومی‌سازی ارقام یک رشته بر اساس زبان: فارسی ← ارقام فارسی، عربی ← ارقام عربی، انگلیسی ← لاتین. */
fun localizedDigits(text: String, lang: AppLang): String = when (lang) {
    AppLang.FA -> TimeFormat.toFaDigits(text)
    AppLang.EN -> text
    AppLang.AR -> {
        val sb = StringBuilder(text.length)
        for (ch in text) {
            sb.append(if (ch in '0'..'9') AR_DIGITS[ch - '0'] else ch)
        }
        sb.toString()
    }
}

/**
 * توصیف نسبی زمان (مثل «۵ دقیقه پیش») به زبان فعال.
 * اگر [timestamp] نامعتبر (۰ یا منفی) باشد، رشته خالی برمی‌گردد.
 */
fun formatRelativeTimeLocalized(
    strings: UiStrings,
    lang: AppLang,
    timestamp: Long,
    now: Long = System.currentTimeMillis()
): String {
    if (timestamp <= 0) return ""
    if (lang == AppLang.FA) return TimeFormat.formatRelativeTimeFa(timestamp, now)
    val diff = (now - timestamp).coerceAtLeast(0)
    fun fmt(pattern: String, value: Long): String =
        localizedDigits(String.format(Locale.US, pattern, value), lang)
    return when {
        diff < 60_000 -> strings.relJustNow
        diff < 3_600_000 -> fmt(strings.relMinutesAgo, diff / 60_000)
        diff < 86_400_000 -> fmt(strings.relHoursAgo, diff / 3_600_000)
        diff < 172_800_000 -> strings.relYesterday
        else -> fmt(strings.relDaysAgo, diff / 86_400_000)
    }
}

/** نمایش شعاع به زبان فعال؛ مثلاً «۵۰۰ متر» / "500 m" / «٥٠٠ م». */
fun formatRadiusLocalized(strings: UiStrings, lang: AppLang, meters: Double): String {
    if (!meters.isFinite() || meters < 0) {
        return "${localizedDigits("0", lang)} ${strings.unitMeter}"
    }
    return if (meters >= 1000.0 && meters % 1000.0 == 0.0) {
        val km = (meters / 1000.0).toLong().toString()
        "${localizedDigits(km, lang)} ${strings.unitKilometer}"
    } else {
        val m = if (meters % 1.0 == 0.0) meters.toLong().toString() else meters.toString()
        "${localizedDigits(m, lang)} ${strings.unitMeter}"
    }
}

